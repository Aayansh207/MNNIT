package logic;

public class Square extends PlaneShape {
    private double side;

    public Square(double side) {
        this.side = side;
    }

    @Override
    public double area() {
        return side * side;
    }

    @Override
    public double perimeter() {
        return 4 * side;
    }

    @Override
    public double diagonal() {
        return side * Math.sqrt(2);
    }
}

