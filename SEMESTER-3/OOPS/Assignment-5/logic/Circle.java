package logic;

public final class Circle {
    private final double radius;
    public Circle(int radius){
        this.radius=radius;
    }

    public Circle(float radius){
        this.radius=radius;
    }

    public Circle(long radius){
        this.radius=radius;
    }

    public Circle(double radius){
        this.radius=radius;
    }

    public double getRadius(){return radius;}
}

